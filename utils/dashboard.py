def _json_safe(obj):
    """numpy scalars and NaN are not JSON-serialisable. NaN becomes null so the
    TS side sees `number | null` rather than a literal NaN token, which is not
    valid JSON and would fail to parse."""
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        f = float(obj)
        return None if np.isnan(f) else f
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if isinstance(obj, pd.Timestamp):
        return str(obj.date())
    raise TypeError(f"not JSON-serialisable: {type(obj)}")


def _players_payload(export_df: pd.DataFrame) -> list:
    """export_df verbatim — the same 14 columns as current_week_export.csv.

    Deliberately not re-derived: the CSV and the dashboard must show identical
    numbers, so they come from one frame. Sorted by P_TOP20 descending to match
    the CSV's order, though the UI sorts client-side anyway."""
    df = export_df.copy()
    if "P_TOP20" in df.columns:
        df = df.sort_values("P_TOP20", ascending=False)
    # NaN -> None per column; .to_dict() would otherwise emit float('nan').
    return json.loads(df.to_json(orient="records", double_precision=6))


def serve_dashboard(port: int = 8765, open_browser: bool = True,
                    root: str = ".") -> str:
    """Serve the repo root on a background thread and open the dashboard.

    Rooted at the REPO, not at dashboard/dist, because the Results Browser
    fetches data/golf.db in place — the 20 MB file is already tracked in git and
    copying it into dashboard/ every week would add a 20 MB blob to history each
    time.

    Idempotent: re-running the cell reuses the already-running server rather
    than failing on a bound port, so the notebook can be run end to end
    repeatedly in one session.
    """
    import functools
    import http.server
    import socket
    import socketserver
    import threading
    import webbrowser

    url = f"http://localhost:{port}/dashboard/dist/index.html"

    def _in_use() -> bool:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            return s.connect_ex(("127.0.0.1", port)) == 0

    if not os.path.exists(os.path.join(DASHBOARD_DIR, "dist", "index.html")):
        print("⚠️ dashboard/dist not built. Run `npm install && npm run build` in dashboard/.")
        return url

    if _in_use():
        print(f"ℹ️ Server already running on port {port} — reusing it.")
    else:
        handler = functools.partial(http.server.SimpleHTTPRequestHandler,
                                    directory=os.path.abspath(root))

        class _Quiet(socketserver.ThreadingTCPServer):
            allow_reuse_address = True
            daemon_threads = True

            def handle_error(self, request, client_address):
                # A browser cancelling a 20 MB golf.db fetch mid-flight raises
                # ConnectionAbortedError here. It is normal and would otherwise
                # dump a traceback into the notebook output every reload.
                pass

        httpd = _Quiet(("127.0.0.1", port), handler)
        threading.Thread(target=httpd.serve_forever, daemon=True).start()
        print(f"✅ Serving {os.path.abspath(root)} on port {port}")

    print(f"   {url}")
    if open_browser:
        webbrowser.open(url)
    return url


def _phases_payload(db_path: str, season: int, players: list) -> dict:
    """Season strokes-gained by phase, from the `stats` table.

    Driving -> SGOTT, Approach -> SGAPR, Around green -> SGATG, Putting -> SGP.

    Ranks come from the DB's own *_RANK columns, which are PGA-Tour-wide, NOT
    field-relative. The card shows them as an absolute anchor; the percentile
    bars and phase flags rank against THIS week's field and are computed in the
    browser from the values. Two different populations, deliberately.

    Coverage is partial by design — the stats table only carries players with
    enough measured rounds (~68% of a DK field). Missing players get an entry
    of nulls rather than no entry, so the UI never distinguishes "absent key"
    from "no data".
    """
    engine = create_engine(f"sqlite:///{db_path}")
    with engine.begin() as conn:
        stats = pd.read_sql(
            "SELECT PLAYER, SGOTT, SGAPR, SGATG, SGP, SGTTG, "
            "SGOTT_RANK, SGAPR_RANK, SGATG_RANK, SGP_RANK, SGTTG_RANK "
            "FROM stats WHERE SEASON = ?",
            conn, params=(int(season),))
    engine.dispose()

    stats = stats.drop_duplicates(subset="PLAYER").set_index("PLAYER")
    # SGTTG is tee-to-green: the OTT + APP + ARG composite, excluding putting.
    # It is a headline number in its own right, not a fifth phase.
    cols = [("ott", "SGOTT"), ("app", "SGAPR"), ("arg", "SGATG"), ("putt", "SGP"),
            ("ttg", "SGTTG")]

    out = {}
    for name in players:
        row = stats.loc[name] if name in stats.index else None
        phases = {}
        for key, col in cols:
            v = None if row is None else row[col]
            r = None if row is None else row[f"{col}_RANK"]
            phases[key] = None if v is None or pd.isna(v) else round(float(v), 4)
            phases[f"{key}_rank"] = None if r is None or pd.isna(r) else int(r)
        out[name] = {"phases": phases}
    return out


HISTORY_DAYS = 730      # the scatter's 24-month window
RESULTS_LIMIT = 40      # recent-results rows per player
LAST_N_STARTS = 20      # window for cuts/top-20 rate and the streak


def _history_payload(t_all: pd.DataFrame, rounds_all: pd.DataFrame,
                     players: list, ending: pd.Timestamp, course: str,
                     ch_present: set) -> dict:
    """Per-player round history, course history and recent results.

    Everything here is derived with the SAME functions that build the model's
    features — build_rounds() for per-round SG, current_streak() for the streak
    — so the card cannot disagree with the model about what it is showing.

    Note this contradicts the design handoff, which claims the only per-event
    quantity in the DB is score and instructs retitling the scatter to "SG per
    event". Per-ROUND SG is real: build_rounds() derives it from ROUNDS:1..4 as
    (that event-round's field mean) minus (the player's score).
    """
    field = set(players)
    # History is strictly before this week — the event being predicted has no
    # results yet, and including it would be lookahead.
    t = t_all[t_all["PLAYER"].isin(field)]
    t = t[t["ENDING_DATE"] < ending]
    all_rounds = rounds_all[rounds_all["PLAYER"].isin(field)]
    all_rounds = all_rounds[all_rounds["ENDING_DATE"] < ending]

    # Per-event SG: the mean of that event's round SGs, over ALL history rather
    # than the scatter's 24-month window. Recent-results rows reach back 40
    # starts and course visits reach back to the player's first appearance, so
    # windowing this would blank the SG column on older rows that do have data.
    ev_sg = (all_rounds.groupby(["PLAYER", "TOURNAMENT", "ENDING_DATE"])["SG"]
             .mean().rename("EV_SG").reset_index())

    # The scatter's window is separate and narrower.
    rounds = all_rounds[all_rounds["ENDING_DATE"] >= ending - pd.Timedelta(days=HISTORY_DAYS)]

    r_by_player = dict(tuple(rounds.sort_values("ENDING_DATE").groupby("PLAYER")))
    t_by_player = dict(tuple(t.groupby("PLAYER")))
    ev_by_player = dict(tuple(ev_sg.groupby("PLAYER")))

    out = {}
    for name in players:
        pr = r_by_player.get(name)
        pt = t_by_player.get(name)

        # --- (e) SG per round, plus the rolling form line ---
        # The trend is an exponentially weighted mean with the model's own
        # 100-day halflife — the same weighting family as SG_FORM, and the same
        # line the Streamlit app draws. It is computed HERE rather than in the
        # browser on purpose: reimplementing pandas' time-based EWMA in JS is
        # exactly the kind of cross-platform port that silently diverges.
        rounds_out = []
        if pr is not None and len(pr):
            # Spread an event's four rounds across four days: round 4 on the
            # ending date, round 1 three days earlier. Off by at most a day for
            # Saturday/Monday finishes. Without this all four rounds share one
            # x-position, which stacks the scatter into vertical columns and
            # turns the trend line into vertical jumps joined by flat steps.
            # Same approximation the Streamlit app uses.
            pr = pr.assign(
                DATE=pr["ENDING_DATE"] - pd.to_timedelta(4 - pr["RND"], unit="D")
            ).sort_values("DATE")
            ser = pr.set_index("DATE")["SG"]
            trend = ser.ewm(halflife=pd.Timedelta(days=SG_HALFLIFE_DAYS),
                            times=ser.index).mean()
            for (d, sg), tv in zip(ser.items(), trend.values):
                rounds_out.append([str(pd.Timestamp(d).date()),
                                   round(float(sg), 2), round(float(tv), 3)])

        rounds_12m = 0
        if pr is not None and len(pr):
            rounds_12m = int((pr["ENDING_DATE"] >= ending - pd.Timedelta(days=365)).sum())

        # --- (c) form profile over the last N starts ---
        cuts_20 = top20_20 = None
        streak = None
        if pt is not None and len(pt):
            recent = pt.sort_values("ENDING_DATE", ascending=False)
            head = recent.head(LAST_N_STARTS)
            cuts_20 = round(float((~head["POS"].isin(["CUT", "W/D"])).mean()) * 100, 0)
            top20_20 = round(float((head["FINAL_POS"] <= 20).mean()) * 100, 0)
            run, kind = current_streak(recent["POS"])
            streak = [int(run), kind] if kind else None

        # --- (g) course history AT THIS WEEK'S COURSE ONLY ---
        # The card is a this-week view, so a scrolling list of every venue the
        # player has ever seen is noise. What matters is depth on the one course
        # being played: how many events, how they finished, and each visit.
        # Other venues live in the Course tab and the Results Browser.
        here = None
        course_events = []
        if pt is not None and len(pt):
            cc = pt[pt["COURSE"] == course]
            if len(cc):
                here = {
                    "ev": int(cc["FINAL_POS"].count()),
                    "avg": round(float(cc["FINAL_POS"].mean()), 1),
                    "best": int(cc["FINAL_POS"].min()),
                    # Percent BEFORE rounding: a frame-wide round(1) on the
                    # fraction quantizes this to the nearest 10%.
                    "cut_pct": int(round(
                        float((~cc["POS"].isin(["CUT", "W/D"])).mean()) * 100)),
                }
                evs = ev_by_player.get(name)
                sg_here = {}
                if evs is not None:
                    sg_here = {(r.TOURNAMENT, r.ENDING_DATE): r.EV_SG
                               for r in evs.itertuples(index=False)}
                for row in cc.sort_values("ENDING_DATE", ascending=False).itertuples(index=False):
                    sg = sg_here.get((row.TOURNAMENT, row.ENDING_DATE))
                    course_events.append({
                        "date": str(pd.Timestamp(row.ENDING_DATE).date()),
                        "tournament": row.TOURNAMENT,
                        "finish": str(row.POS),
                        "sg": None if sg is None or pd.isna(sg) else round(float(sg), 2),
                    })

        # --- (h) recent results ---
        results = []
        if pt is not None and len(pt):
            evs = ev_by_player.get(name)
            sg_lookup = {}
            if evs is not None:
                sg_lookup = {(r.TOURNAMENT, r.ENDING_DATE): r.EV_SG
                             for r in evs.itertuples(index=False)}
            recent = pt.sort_values("ENDING_DATE", ascending=False).head(RESULTS_LIMIT)
            for row in recent.itertuples(index=False):
                sg = sg_lookup.get((row.TOURNAMENT, row.ENDING_DATE))
                results.append({
                    "date": str(pd.Timestamp(row.ENDING_DATE).date()),
                    "tournament": row.TOURNAMENT,
                    "finish": str(row.POS),
                    "sg": None if sg is None or pd.isna(sg) else round(float(sg), 2),
                })

        out[name] = {
            "rounds_12m": rounds_12m,
            "cuts_20": cuts_20,
            "top20_20": top20_20,
            "streak": streak,
            "rounds": rounds_out,
            "course_here": here,
            "course_events": course_events,
            # Whether SG_CH_SHRUNK is a REAL measurement for this player, i.e.
            # they have rounds at this course inside the model's 7-year window.
            #
            # This cannot be inferred from the exported value being 0. The CSV
            # rounds to 2 decimals, and a player who performed at exactly field
            # average rounds to 0.0 — Beau Hossler is -0.0045 over 6 events at
            # Detroit. An absent player is ALSO 0 (NaN filled). Treating 0 as
            # "no history" mislabels the genuinely-average players, so presence
            # is published explicitly instead.
            "ch_window": name in ch_present,
            "results": results,
        }
    return out


SG_TREND_DAYS = 30          # lookback for the SG-rankings rank movement
SG_SPARK_ROUNDS = 20
COURSE_MIN_ROUNDS = 4       # floor for appearing in the course table at all


def _sg_rankings_payload(rounds: pd.DataFrame, ending: pd.Timestamp) -> list:
    """SG form for EVERY active player, with rank movement and a sparkline.

    This is the Streamlit app's "SG Rankings" view. It is deliberately NOT
    restricted to this week's DK field — the point of the view is to see who is
    playing well across the whole tour, including players not in this field.

    SG_FORM comes from sg_features_for_event(), the same function that builds
    the model's feature, so the numbers reconcile with the export.
    """
    now = sg_features_for_event(rounds, ending)
    if now.empty:
        return []
    now = now.sort_values("SG_FORM", ascending=False).reset_index(drop=True)
    now["RANK"] = np.arange(1, len(now) + 1)

    prev = sg_features_for_event(rounds, ending - pd.Timedelta(days=SG_TREND_DAYS))
    if not prev.empty:
        prev = prev.sort_values("SG_FORM", ascending=False).reset_index(drop=True)
        prev["PREV_RANK"] = np.arange(1, len(prev) + 1)
        now = now.merge(prev[["PLAYER", "PREV_RANK"]], on="PLAYER", how="left")
    else:
        now["PREV_RANK"] = np.nan

    recent = rounds[rounds["ENDING_DATE"] >= ending - pd.Timedelta(days=HISTORY_DAYS)]
    spark = (recent.sort_values("ENDING_DATE").groupby("PLAYER")["SG"]
             .apply(lambda x: [round(float(v), 2) for v in x.tail(SG_SPARK_ROUNDS)]))

    out = []
    for row in now.itertuples(index=False):
        move = None
        if pd.notna(row.PREV_RANK):
            move = int(row.PREV_RANK - row.RANK)   # positive = climbed
        out.append({
            "rank": int(row.RANK),
            "player": row.PLAYER,
            "sg_form": round(float(row.SG_FORM), 4),
            "rounds_12m": int(row.SG_ROUNDS_12M),
            "move": move,
            "spark": spark.get(row.PLAYER, []),
        })
    return out


def _course_payload(t: pd.DataFrame, rounds: pd.DataFrame, course: str,
                    ending: pd.Timestamp, model_sg: pd.DataFrame) -> dict:
    """Horses for courses at THIS week's venue, measured in strokes.

    Only this week's course is precomputed. Every course would be ~20k rows and
    roughly double the payload, and the model's SG_CH_SHRUNK is a shrunk
    7-year window that would have to be reimplemented in SQL to compute other
    courses in the browser — exactly the kind of port that silently disagrees
    with the feature the model was actually trained on. Other venues remain
    reachable through the Results Browser.

    SG (model) is sg_at_course_for_event() itself, so this table reconciles
    with SG_CH_SHRUNK in the export. SG (raw) is the plain unshrunk mean, for
    intuition about sample size.
    """
    sub_t = t[(t["COURSE"] == course) & (t["ENDING_DATE"] < ending)]
    sub_r = rounds[(rounds["COURSE"] == course) & (rounds["ENDING_DATE"] < ending)]
    if sub_t.empty:
        return {"course": course, "events": 0, "first_year": None,
                "last_year": None, "players": []}

    res = (sub_t.groupby("PLAYER")
           .agg(events=("FINAL_POS", "count"),
                best=("FINAL_POS", "min"),
                avg_finish_pct=("FINISH_PCT", "mean"),
                cuts=("POS", lambda x: (~x.isin(["CUT", "W/D"])).mean()),
                last_played=("ENDING_DATE", "max")))

    sg = (sub_r.groupby("PLAYER")
          .agg(course_rounds=("SG", "count"), sg_raw=("SG", "mean")))

    ce = res.join(sg, how="inner").reset_index().merge(model_sg, on="PLAYER", how="left")
    ce = ce[ce["course_rounds"] >= COURSE_MIN_ROUNDS]
    ce = ce.sort_values("SG_CH_SHRUNK", ascending=False)

    players = []
    for row in ce.itertuples(index=False):
        players.append({
            "player": row.PLAYER,
            "sg_model": None if pd.isna(row.SG_CH_SHRUNK) else round(float(row.SG_CH_SHRUNK), 3),
            "sg_raw": round(float(row.sg_raw), 3),
            "rounds": int(row.course_rounds),
            "events": int(row.events),
            "avg_finish_pct": round(float(row.avg_finish_pct), 3),
            "cut_pct": int(round(float(row.cuts) * 100)),
            "best": int(row.best),
            "last_played": int(pd.Timestamp(row.last_played).year),
        })

    evs = sub_t[["TOURNAMENT", "ENDING_DATE"]].drop_duplicates()
    return {
        "course": course,
        "events": int(len(evs)),
        "first_year": int(sub_t["ENDING_DATE"].min().year),
        "last_year": int(sub_t["ENDING_DATE"].max().year),
        "players": players,
    }


TOP_N = 15


def _weeks_payload(j: pd.DataFrame) -> list:
    """Per-week track record: of the model's 15 highest P_TOP20, how many
    finished top-20, and their cut rate. Baseline is 6.49 hits, from the
    forward-chained eval in experiments/forward_eval.py.

    Uses the SAME pandas nlargest() call as utils.model.grade_predictions()
    rather than re-selecting the top 15 in a hand-rolled sort. That is not
    fussiness: P_TOP20 is rounded to 3 decimals when logged, so ties at the
    15-player boundary are common (the 2026 3M Open had a three-way tie at
    0.301), and two different tie-breaks silently disagree about the cut rate.
    One selection, one answer, in both views.
    """
    out = []
    for (tourn, date), grp in j.groupby(["TOURNAMENT", "ENDING_DATE"]):
        graded = grp["FINAL_POS"].notna().any()
        top15 = grp.nlargest(TOP_N, "P_TOP20")
        out.append({
            "date": str(pd.Timestamp(date).date()),
            "tournament": tourn,
            "players": int(len(grp)),
            "graded": bool(graded),
            "expected": round(float(top15["P_TOP20"].sum()), 1),
            "hits": int((top15["FINAL_POS"] <= 20).sum()) if graded else None,
            # Read from POS, not inferred from FINAL_POS: 90 is the DB's fill
            # value for CUT/WD, so a numeric threshold would conflate a genuine
            # 90th-place finish with a missed cut. Same test Streamlit uses.
            "cut_rate": (int(round(100 * float(
                (~top15["POS"].isin(["CUT", "W/D"])).mean())))
                if graded else None),
        })
    return sorted(out, key=lambda w: w["date"], reverse=True)


def _tracker_payload(db_path: str):
    """Logged predictions joined to actual finishes, for the Prediction Tracker.

    The join is (TOURNAMENT, ENDING_DATE, PLAYER) — there are no event or player
    IDs in this schema. The design handoff's stub SQL assumed event_id/player_id
    and a p_top20_pred column; none of those exist. This mirrors the join in
    utils.model.grade_predictions().

    Returns (rows, joined_frame) — the frame is handed to _weeks_payload() so
    the per-week table and the per-player calibration rows are built from one
    join rather than two.
    """
    engine = create_engine(f"sqlite:///{db_path}")
    with engine.begin() as conn:
        try:
            preds = pd.read_sql(
                "SELECT TOURNAMENT, ENDING_DATE, PLAYER, P_TOP20 FROM predictions", conn)
        except Exception:
            engine.dispose()
            return [], pd.DataFrame()
        results = pd.read_sql(
            "SELECT TOURNAMENT, ENDING_DATE, PLAYER, POS, FINAL_POS FROM tournaments", conn)
    engine.dispose()

    if preds.empty:
        return [], pd.DataFrame()

    j = preds.merge(results, on=["TOURNAMENT", "ENDING_DATE", "PLAYER"], how="left")

    # `j` is returned UNSORTED, in the order read_sql produced. That matters:
    # nlargest() breaks ties by row order, P_TOP20 is logged rounded to 3
    # decimals so boundary ties are common, and grade_predictions() groups the
    # unsorted frame. Sorting here would reshuffle which tied player lands in
    # the top 15 and make this table disagree with the notebook's report card
    # for the same week. Only the display copy below is sorted.
    out = []
    for row in j.sort_values("ENDING_DATE", ascending=False).itertuples(index=False):
        graded = pd.notna(row.FINAL_POS)
        out.append({
            "date": str(pd.Timestamp(row.ENDING_DATE).date()),
            "tournament": row.TOURNAMENT,
            "player": row.PLAYER,
            "p_top20": None if pd.isna(row.P_TOP20) else round(float(row.P_TOP20), 4),
            "finish": int(row.FINAL_POS) if graded else None,
            "pos": None if pd.isna(row.POS) else str(row.POS),
            "hit": bool(row.FINAL_POS <= 20) if graded else None,
        })
    return out, j


def export_dashboard(db_path: str, export_df: pd.DataFrame, config: dict,
                     verbose: bool = True) -> dict:
    """Write dashboard/public/data/slate.js (and mirror into dist/ if built).

    Publishes meta, the scored field, season SG-by-phase, per-player round /
    course / results history, and the graded prediction log.
    """
    new = config["new"]
    ending = pd.Timestamp(new["ending_date"])

    players = _players_payload(export_df)
    names = [p["PLAYER"] for p in players]

    # Loaded once and shared: build_rounds() unpivots ~56k tournament rows into
    # ~200k round rows, and three of the payloads below need it.
    t_all, _s, _o = load_tables(db_path)
    rounds_all = build_rounds(t_all)

    # Computed once and shared. Presence in this frame — not a rounded zero in
    # the CSV — is what tells the UI whether SG_CH_SHRUNK is a real measurement.
    model_sg = sg_at_course_for_event(rounds_all, ending, new["course"])
    ch_present = set(model_sg["PLAYER"])

    form = _phases_payload(db_path, int(new["season"]), names)
    history = _history_payload(t_all, rounds_all, names, ending, new["course"], ch_present)
    for name in names:
        form[name].update(history.get(name, {}))

    tracker, tracker_join = _tracker_payload(db_path)
    weeks = _weeks_payload(tracker_join) if len(tracker_join) else []
    sg_rankings = _sg_rankings_payload(rounds_all, ending)
    course = _course_payload(t_all, rounds_all, new["course"], ending, model_sg)

    slate = {
        "meta": {
            "tournament": new["name"],
            "course": new["course"],
            "ending_date": str(ending.date()),
            "season": int(new["season"]),
            "field_size": len(players),
            "generated_at": datetime.now(timezone.utc)
                            .isoformat(timespec="seconds"),
            "cap": DK_CAP,
            "roster": DK_ROSTER,
        },
        "players": players,
        "form": form,
        "tracker": tracker,
        "weeks": weeks,
        "sg_rankings": sg_rankings,
        "course": course,
    }

    payload = json.dumps(slate, default=_json_safe, separators=(",", ":"))
    body = (
        "// Generated by utils/dashboard.py — do not edit.\n"
        "// Regenerated every time the notebook's Export cell runs.\n"
        f"window.SLATE = {payload};\n"
    )

    written = []
    os.makedirs(PUBLIC_DATA, exist_ok=True)
    primary = os.path.join(PUBLIC_DATA, SLATE_FILENAME)
    with open(primary, "w", encoding="utf-8") as f:
        f.write(body)
    written.append(primary)

    # Only mirror into dist/ when a build already exists — creating the folder
    # would fake a built app that cannot actually load.
    if os.path.isdir(os.path.dirname(DIST_DATA)):
        os.makedirs(DIST_DATA, exist_ok=True)
        mirror = os.path.join(DIST_DATA, SLATE_FILENAME)
        shutil.copyfile(primary, mirror)
        written.append(mirror)

    if verbose:
        kb = len(body.encode("utf-8")) / 1024
        with_stats = sum(1 for v in form.values() if v["phases"]["ott"] is not None)
        n_rounds = sum(len(v.get("rounds", [])) for v in form.values())
        graded = sum(1 for r in tracker if r["finish"] is not None)
        print(f"✅ Dashboard slate → {len(players)} players, {kb:.0f} KB")
        print(f"   {with_stats} with {new['season']} SG stats · {n_rounds:,} rounds · "
              f"{len(tracker)} tracked predictions ({graded} graded)")
        print(f"   SG rankings {len(sg_rankings)} players · "
              f"{course['course']}: {len(course['players'])} players / "
              f"{course['events']} events")
        for p in written:
            print(f"   → {p}")
        if len(written) == 1:
            print("   (dist/ not built yet — run `npm run build` in dashboard/)")

    return slate
